export type AssetStatus = 'Available' | 'Integrated' | 'Needs Optimization' | 'Missing' | 'Rejected'
export type AssetGroup =
  'background' | 'foreground' | 'midground' | 'gallery' | 'brand' | 'motion' | 'sections'

export interface AuxiliaryAsset {
  id: string
  name: string
  group: AssetGroup
  paths: string[]
  dimensions: string | null
  format: string | null
  transparency: 'yes' | 'no' | 'not applicable' | 'unknown'
  source: string | null
  intendedSection: string
  layer: string
  status: AssetStatus
}

const missing = (
  id: string,
  name: string,
  group: AssetGroup,
  intendedSection: string,
  layer: string,
): AuxiliaryAsset => ({
  id,
  name,
  group,
  paths: [],
  dimensions: null,
  format: null,
  transparency: 'unknown',
  source: null,
  intendedSection,
  layer,
  status: 'Missing',
})

const image = (
  id: string,
  name: string,
  group: AssetGroup,
  path: string,
  dimensions: string,
  transparency: 'yes' | 'no',
  intendedSection: string,
  layer: string,
  source: string,
): AuxiliaryAsset => ({
  id,
  name,
  group,
  paths: [path],
  dimensions,
  format: path.endsWith('.webp') ? 'WebP' : 'PNG',
  transparency,
  source,
  intendedSection,
  layer,
  status: 'Integrated',
})

const code = (
  id: string,
  name: string,
  group: AssetGroup,
  path: string,
  intendedSection: string,
  layer: string,
): AuxiliaryAsset => ({
  id,
  name,
  group,
  paths: [path],
  dimensions: 'Responsive CSS/DOM',
  format: 'HTML/CSS',
  transparency: 'not applicable',
  source: 'Original project implementation',
  intendedSection,
  layer,
  status: 'Integrated',
})

